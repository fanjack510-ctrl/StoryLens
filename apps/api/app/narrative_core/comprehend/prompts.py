"""「读懂」的提示词。

三条贯穿始终：

**要判断，不要话题。** 「本节讨论了颜色原理」对读者毫无用处——他想知道的是这一节**断定了
什么**。所以提示词里把这条写成硬要求，并给了正反例。

**不许编，宁可空着。** 这条读法的产出会被当成原文的替代品。小说那边说错一句是可争论的读法，
知识类书说错一句就是一个错的事实。所以「本节未给操作」是合格答案，编一个不是。

**短。** 读者要这份东西，是因为没时间读原文；摘要跟正文一样长，就等于没摘要。实测第一版
写了 4.8 万字（原书的 10.5%），其中三分之一花在复述原文对依据的描述上——那是书里本来就有的
东西，读者需要的只是「引了谁」，好让他翻回去核对。

**用中文回答，但术语留原文。** 用户的需求正是「读不动英文」。可如果把 `Sequential mapping`
也译掉，他回到原文里就找不着了——摘要的价值恰恰在于能带他回到原文。
"""

from __future__ import annotations

from app.narrative_core.comprehend.planner import DigestUnit

__all__ = ["build_section_prompt", "build_chapter_prompt", "build_book_prompt"]


_SECTION_RULES = """\
请用中文回答，严格按下面五段输出，每段以「## 」开头，不要写任何客套话。

## 主张
这一节断定了什么。3–6 条，每条一句话，必须是**判断**不是话题。
  ✗ 讨论了颜色在数据可视化中的作用
  ✓ 分类数据应当用色相区分，且类别数不宜超过 12 种
如果这一节确实只是过渡、没有主张，就写「本节未提出主张」。

## 依据
**只列出处，不要复述原文。** 格式：作者 年份，多个用「、」隔开，最多 6 个。
  ✗ 原文引用 Friendly（2006）指出图形通信可追溯到公元前二世纪，并引用……
  ✓ Friendly 2006、Der & Everitt 2015、Tufte 2001
原文没有具名出处但给了原理性依据（如「基于人眼视锥细胞的生理机制」），就写那一句，20 字以内。
原文没给依据就写「本节未给出依据」——**不要替它补一个**。

## 做法
读者能照着做的动作，最多 3 条。没有就写「本节未给操作」。

## 术语
这一节真正**定义**或反复使用的词，**最多 5 个**。格式：原文词（中文）。没有就写「无」。
只是提到一次的名词不算术语——列进来就成了词表，不是摘要。

## 存疑
这一节没有回答、但读者会自然追问的问题，**最多 1 条，30 字以内**。没有就写「无」。

硬要求：
· 只根据下面的原文作答。原文里没有的，一个字也不要加。
· 术语保留原文词，因为读者要能拿它回到原文里去找。
· 不确定的地方宁可写「原文未明确」，也不要给一个像样的猜测。
"""


def build_section_prompt(unit: DigestUnit, *, book_title: str) -> str:
    heads = "、".join(s.display_title for s in unit.sections)
    part = "" if unit.part_count == 1 else f"（这是本节的第 {unit.part} 片，共 {unit.part_count} 片）"
    body = "\n\n".join(
        f"【{s.display_title}】\n" + "\n".join(s.paragraphs) for s in unit.sections
    )
    return (
        f"下面是《{book_title}》中的原文，涵盖：{heads}{part}\n\n"
        f"{_SECTION_RULES}\n"
        f"----- 原文开始 -----\n{body}\n----- 原文结束 -----\n"
    )


def build_chapter_prompt(chapter: str, title: str, section_claims: list[str]) -> str:
    """章级上卷。只喂下级的主张，不再喂原文——原文已经被读过一遍，再喂一遍是重复付费。"""
    joined = "\n".join(f"· {c}" for c in section_claims)
    return (
        f"下面是《{chapter} {title}》各节的主张清单。请用中文输出两段，每段以「## 」开头：\n\n"
        "## 这一章讲了什么\n"
        "一段话，150 字以内。要说清这一章的**立场**，不是罗列小节标题。\n\n"
        "## 这一章的主线\n"
        "一句话：这些主张是怎么串成一条线的（从什么问题出发，落到什么结论）。\n"
        "如果它们其实各自独立、并没有一条主线，就直说「本章是并列的若干专题，没有单一主线」——\n"
        "**编一条不存在的主线，比承认没有更糟。**\n\n"
        f"----- 主张清单 -----\n{joined}\n"
    )


def build_book_prompt(book_title: str, chapter_lines: list[str]) -> str:
    joined = "\n".join(chapter_lines)
    return (
        f"下面是《{book_title}》各章的要点。请用中文输出四段，每段以「## 」开头：\n\n"
        "## 一段话说清这本书\n"
        "200 字以内。假设读者完全没读过，也不打算读。\n\n"
        "## 全书的主张\n"
        "这本书整体在主张什么。若它是一本论文集/手册、各章互不隶属，就直说，不要硬拧一个主题。\n\n"
        "## 读完能带走什么\n"
        "3 条以内，具体到「知道了什么」或「会做什么」，不要写「拓宽视野」这类空话。\n\n"
        "## 谁该读、谁不必读\n"
        "各一句。**明确说出谁不必读**——对读者来说，「这本书不适合你」和「适合你」一样有用。\n\n"
        f"----- 各章要点 -----\n{joined}\n"
    )
