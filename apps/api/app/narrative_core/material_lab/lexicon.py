def emotion_of(text: str) -> tuple[str, float]:
    best, best_n = "", 0
    for emo, words in EMOTION_LEX.items():
        n = sum(text.count(w) for w in words)
        if n > best_n:
            best, best_n = emo, n
    density = best_n / max(len(text), 1) * 1000
    return best, round(density, 3)


